#!/usr/bin/env sh
set -eu

failures=0

require_file() {
  if [ ! -f "$1" ]; then
    printf 'missing file: %s\n' "$1"
    failures=$((failures + 1))
  fi
}

require_text() {
  file="$1"
  text="$2"
  label="$3"

  if [ ! -f "$file" ]; then
    printf 'missing file for text check: %s\n' "$file"
    failures=$((failures + 1))
    return
  fi

  if ! grep -F "$text" "$file" >/dev/null 2>&1; then
    printf 'missing text: %s in %s\n' "$label" "$file"
    failures=$((failures + 1))
  fi
}

